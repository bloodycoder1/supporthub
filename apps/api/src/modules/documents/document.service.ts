
import { unlink } from "node:fs/promises";
import path from "node:path";
import mongoose from "mongoose";
import { DocumentModel } from "./document.model";
import { WorkspaceModel } from "../workspaces/workspace.model";

export async function saveUploadedDocument(
  workspaceId: string,
  userId: string,
  file: Express.Multer.File
) {
  if (!mongoose.isValidObjectId(workspaceId)) {
    throw Object.assign(new Error("Workspace not found"), {
      statusCode: 404,
    });
  }

  const workspace = await WorkspaceModel.findOne({
    _id: workspaceId,
    ownerId: userId,
  }).select("_id");

  if (!workspace) {
    throw Object.assign(new Error("Workspace not found"), {
      statusCode: 404,
    });
  }

  try {
    const document = await DocumentModel.create({
      workspaceId: workspace._id,
      uploadedBy: new mongoose.Types.ObjectId(userId),
      originalName: path.basename(file.originalname),
      mimeType: file.mimetype,
      size: file.size,
      storageKey: path.basename(file.filename),
      status: "uploaded",
    });

    return {
      id: document.id,
      workspaceId: document.workspaceId.toString(),
      originalName: document.originalName,
      mimeType: document.mimeType,
      size: document.size,
      status: document.status,
      createdAt: document.createdAt,
    };
  } catch (error) {
    // Remove the physical file if saving metadata fails.
    await unlink(file.path).catch(() => undefined);
    throw error;
  }
}


export async function listWorkspaceDocuments(
  workspaceId: string,
) {
  if (!mongoose.isValidObjectId(workspaceId)) {
    const error = new Error("Workspace not found");
    Object.assign(error, { statusCode: 404 });
    throw error;
  }

  const documents = await DocumentModel.find({ workspaceId })
    .select(
      "_id workspaceId originalName mimeType size status createdAt updatedAt",
    )
    .sort({ createdAt: -1 })
    .lean();

  return documents.map((document) => ({
    id: document._id.toString(),
    workspaceId: document.workspaceId.toString(),
    originalName: document.originalName,
    mimeType: document.mimeType,
    size: document.size,
    status: document.status,
    createdAt: document.createdAt,
    updatedAt: document.updatedAt,
  }));
}


export async function deleteWorkspaceDocument(
  workspaceId: string,
  documentId: string,
) {
  const document = await DocumentModel.findOne({
    _id: documentId,
    workspaceId,
  });

  if (!document) {
    return false;
  }

  // Storage keys are generated by the server, not supplied by users.
  const storageKey = document.storageKey;

  if (
    !storageKey ||
    path.basename(storageKey) !== storageKey
  ) {
    throw new Error("Invalid document storage key");
  }

  // Remove the database record first.
  await DocumentModel.deleteOne({
    _id: document._id,
    workspaceId,
  });

  // Then remove the private file.
  const uploadDirectory = path.resolve(
    process.cwd(),
    "private_uploads",
  );

  try {
    await unlink(path.join(uploadDirectory, storageKey));
  } catch (error) {
    // A missing file is already effectively deleted.
    if (
      !(error instanceof Error && "code" in error &&
        error.code === "ENOENT")
    ) {
      throw error;
    }
  }

  return true;
}
